def test_freeform_option_has_no_suggestions(tmp_path):
    script = _script(tmp_path)
    result = _complete(script, ["tvmgr", "discover", "--network", ""], 3)
    assert result.stdout.strip() == ""
    result = _complete(script, ["tvmgr", "discover", "--timeout", ""], 3)
    assert result.stdout.strip() == ""
    result = _complete(script, ["tvmgr", "discover", "--network=x"], 2)
    assert result.stdout.strip() == ""
