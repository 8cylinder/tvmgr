def test_install_writes_path_and_mode(monkeypatch, tmp_path, capsys):
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path))
    destination = completions.install_bash_completion(main, "tvmgr", "0.2.0")
    captured = capsys.readouterr()

    assert destination == (
        tmp_path / "bash-completion" / "completions" / "tvmgr.bash"
    )
    assert captured.out.strip() == str(destination)
    assert f"source {destination}" in captured.err
    assert destination.stat().st_mode & 0o777 == 0o644
    assert "complete -o nosort" in destination.read_text()


def test_install_overwrites_existing(monkeypatch, tmp_path):
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path))
    destination = completions.install_bash_completion(main, "tvmgr", "0.2.0")
    destination.write_text("old")
    completions.install_bash_completion(main, "tvmgr", "0.2.0")
    assert "Generated by the application" in destination.read_text()


def test_generated_script_passes_bash_syntax_check(tmp_path):
    script = _script(tmp_path)
    result = subprocess.run(
        ["bash", "-n", str(script)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr


