def test_bash_probe_oserror_is_ignored(monkeypatch, tmp_path, capsys):
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path))
    monkeypatch.setattr(completions.shutil, "which", lambda _: "/bin/bash")

    def fail(*args, **kwargs):
        raise OSError("nope")

    monkeypatch.setattr(completions.subprocess, "run", fail)
    completions.install_bash_completion(main, "tvmgr", "0.2.0")
    assert "older than" not in capsys.readouterr().err


def test_invalid_destination_is_cleaned_up(monkeypatch, tmp_path):
    monkeypatch.setenv("XDG_DATA_HOME", str(tmp_path))
    monkeypatch.setattr(
        completions,
        "generate_bash",
        lambda *_args, **_kwargs: "echo",
    )

    # Make the destination a directory so the atomic replace fails.
    destination = tmp_path / "bash-completion" / "completions" / "tvmgr.bash"
    destination.mkdir(parents=True)
    with pytest.raises(OSError):
        completions.install_bash_completion(main, "tvmgr", "0.2.0")
    leftovers = list(destination.parent.glob(".tvmgr.*.tmp"))
    assert leftovers == []


