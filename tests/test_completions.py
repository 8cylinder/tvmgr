def test_hidden_commands_and_options_are_excluded(tmp_path):
    @click.group()
    def sample() -> None:
        pass

    @sample.command(hidden=True)
    def secret() -> None:
        pass

    @sample.command()
    @click.option("--hidden-option", hidden=True)
    @click.option("--visible-option", type=click.Choice(["a", "b"]))
    def visible(hidden_option: str, visible_option: str) -> None:
        pass

    script = completions.generate_bash(sample, "sample", "1.0")
    assert "secret" not in script
    assert "hidden-option" not in script
    assert "visible-option" in script


